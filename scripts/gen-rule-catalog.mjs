#!/usr/bin/env node
// Generates src/core/rule-catalog.js from docs/rules.md ("### R-ID — title" blocks).
// Usage: node scripts/gen-rule-catalog.mjs [--check]   (--check: exit 1 if the committed file is stale)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const md = readFileSync(join(ROOT, 'docs', 'rules.md'), 'utf8');
const version = (/რეესტრის ვერსია:\s*`([^`]+)`/.exec(md) || [])[1] || null;
const blocks = md.split(/^### /m).slice(1);
const catalog = {};
for (const b of blocks) {
  const head = /^(R-[A-Z0-9-]+)(?:\s+—\s+(.+))?\s*$/.exec(b.split('\n')[0]);
  if (!head) continue;
  const id = head[1];
  let title = head[2];
  if (!title) {
    const desc = /^- (?:აღწერა|ციტატა):\s*(.+)$/m.exec(b);
    title = desc ? desc[1].replace(/^„…?/, '').slice(0, 80).replace(/\s+\S*$/, '') + '…' : id;
  }
  const body = b.split(/^## /m)[0];
  const src = /წყარო:\s*([^\n]*?)(?:\.\s+სტატუსი:|\.\s+ტესტები:|$)/m.exec(body);
  const stIdx = body.indexOf('სტატუსი:');
  let status = [];
  if (stIdx >= 0) {
    const tail = body.slice(stIdx + 'სტატუსი:'.length).split(/\n|\.\s/)[0];
    status = [...tail.matchAll(/`([a-z-]+)`/g)].map((m) => m[1]);
  }
  if (catalog[id]) throw new Error(`duplicate rule ${id}`);
  catalog[id] = { title_ka: title.trim(), source: src ? src[1].trim().replace(/\.$/, '') : null, status: status.length ? status : ['unspecified'] };
}
// table rows: | R-ID | point | content | `status` | in-calculator |
for (const m of md.matchAll(/^\|\s*(R-[A-Z0-9-]+)\s*\|\s*([^|]*)\|\s*([^|]*)\|\s*([^|]*)\|\s*([^|]*)\|\s*$/gm)) {
  const [, id, point, content, st, inCalc] = m;
  if (catalog[id]) continue;
  catalog[id] = { title_ka: content.trim(), source: point.trim(),
    status: [...st.matchAll(/`([a-z-]+)`/g)].map((x) => x[1]).concat(inCalc.trim() ? [inCalc.trim().split(/\s/)[0]] : []) };
}
const ids = Object.keys(catalog);
const out = `// GENERATED by scripts/gen-rule-catalog.mjs from docs/rules.md — do not edit by hand.
// rules registry version: ${version}; ${ids.length} rules.
export const RULES_REGISTRY_VERSION = ${JSON.stringify(version)};

/** @type {Readonly<Record<string, { title_ka: string, source: string|null, status: string[] }>>} */
export const ruleCatalog = Object.freeze(${JSON.stringify(catalog, null, 1)});

export const RULE_IDS = Object.freeze(Object.keys(ruleCatalog));
export const hasRule = (id) => Object.prototype.hasOwnProperty.call(ruleCatalog, id);
`;
const target = join(ROOT, 'src', 'core', 'rule-catalog.js');
if (process.argv.includes('--check')) {
  let cur = '';
  try { cur = readFileSync(target, 'utf8'); } catch {}
  if (cur !== out) { console.error('rule-catalog.js is stale; run node scripts/gen-rule-catalog.mjs'); process.exit(1); }
  console.log(`rule-catalog.js up to date (${ids.length} rules)`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target} (${ids.length} rules)`);
}
